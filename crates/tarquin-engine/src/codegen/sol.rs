//! EN-O2 — the Solidity backend: Rule IR → `primitives/src/generated/RuleEngineV01.sol`,
//! plus the generated parity test (`primitives/test/generated/RuleEngineParity.t.sol`) that
//! replays the golden corpus on-chain.
//!
//! Encoding map (the parity-critical artifact):
//! - `LegSubtype`  → `Types.LegSubtype` (UNSET-offset enum already in `Types.sol`)
//! - `Action`      → `Types.Action`
//! - `VerificationRegime` → generated `RuleEngineV01.VerificationRegime` (UNSET-offset)
//! - `reason_code` / rule ids → `bytes32` of the UTF-8 string, right-padded
//! - conjunction   → `&&`; rule order → first-match-wins over the governing order

use crate::ir::{Condition, Rule};

use super::{
    action_str, governing_order, regime_screaming, ruleset_hash, subtype_str, CodegenError,
    CorpusCase,
};

const HEADER: &str = "\
// SPDX-License-Identifier: Apache-2.0
// ─────────────────────────────────────────────────────────────────────────────
// GENERATED FILE — DO NOT EDIT BY HAND.
// Generated by `tarquin-engine-gen` (crates/tarquin-engine) from the canonical
// Rule IR. Regenerate:  cargo run -p tarquin-engine --bin tarquin-engine-gen
// Drift check (CI):     cargo run -p tarquin-engine --bin tarquin-engine-gen -- --check
// ─────────────────────────────────────────────────────────────────────────────
";

/// Generate the on-chain evaluator library.
pub fn generate(rules: &[Rule]) -> Result<String, CodegenError> {
    let ordered = governing_order(rules)?;
    let hash = ruleset_hash(rules);

    let mut s = String::new();
    s.push_str(HEADER);
    s.push_str(&format!("// ruleset_sha256: {hash}\n"));
    s.push_str("pragma solidity ^0.8.28;\n\n");
    s.push_str("import {Types} from \"../core/Types.sol\";\n\n");
    s.push_str(
        "/// @title RuleEngineV01 — on-chain compilation of the Tarquin Rule IR (v0.1).\n\
         /// @notice Semantics are identical to `tarquin-engine::evaluate`: rules are emitted in\n\
         ///         governing order (forced first, then restrictiveness, then id) and the first\n\
         ///         match wins; no match fails closed to HL (ENG-DEFAULT-HL).\n\
         library RuleEngineV01 {\n",
    );
    s.push_str(
        "    /// Mirrors `tarquin_sibyl::registry::VerificationRegime` with a Solidity UNSET slot.\n\
         \x20   enum VerificationRegime {\n\
         \x20       UNSET,\n\
         \x20       STRUCTURED_LEGAL_ATTESTATION,\n\
         \x20       MULTIPLE_LEGAL_ATTESTATION,\n\
         \x20       INSTITUTIONAL_ATTESTATION\n\
         \x20   }\n\n",
    );
    s.push_str(
        "    /// Mirrors `tarquin_engine::ir::Inputs`. `reasonCode` is the UTF-8 reason string\n\
         \x20   /// right-padded into bytes32 (e.g. `bytes32(\"SA\")`).\n\
         \x20   struct Inputs {\n\
         \x20       Types.LegSubtype legSubtype;\n\
         \x20       uint8 finality;\n\
         \x20       bytes32 reasonCode;\n\
         \x20       VerificationRegime verificationRegime;\n\
         \x20       bool sibylRegisteredActive;\n\
         \x20       bool proofInstrumentSpecific;\n\
         \x20       bool lexcodexPermitsPr;\n\
         \x20   }\n\n",
    );
    s.push_str(
        "    /// Mirrors `tarquin_engine::eval::Decision`. `ruleId` is the rule id right-padded\n\
         \x20   /// into bytes32.\n\
         \x20   struct Decision {\n\
         \x20       Types.Action action;\n\
         \x20       bool forced;\n\
         \x20       bytes32 ruleId;\n\
         \x20   }\n\n",
    );
    s.push_str(&format!(
        "    /// sha256 of the canonical Rule IR JSON this file was generated from.\n\
         \x20   bytes32 internal constant RULESET_SHA256 = 0x{hash};\n\n"
    ));
    s.push_str(
        "    /// Total, deterministic, pure. Same inputs -> same Decision as every other target.\n\
         \x20   function evaluate(Inputs memory i) internal pure returns (Decision memory) {\n",
    );
    for r in &ordered {
        s.push_str(&format!(
            "        // {} ({}) -> {} — parity: {}\n",
            r.id,
            if r.forced { "forced" } else { "overridable" },
            action_str(r.yields),
            r.parity_ref
        ));
        let conds: Vec<String> = r.when.iter().map(condition_sol).collect();
        s.push_str(&format!("        if ({}) {{\n", conds.join(" && ")));
        s.push_str(&format!(
            "            return Decision(Types.Action.{}, {}, bytes32(\"{}\"));\n",
            action_str(r.yields),
            r.forced,
            r.id
        ));
        s.push_str("        }\n");
    }
    s.push_str(
        "        // No rule matched: fail closed (EN-003).\n\
         \x20       return Decision(Types.Action.HL, false, bytes32(\"ENG-DEFAULT-HL\"));\n\
         \x20   }\n\
         }\n",
    );
    Ok(s)
}

fn condition_sol(c: &Condition) -> String {
    match c {
        Condition::SubtypeEquals(s) => {
            format!("i.legSubtype == Types.LegSubtype.{}", subtype_str(*s))
        }
        Condition::FinalityEquals(f) => format!("i.finality == {f}"),
        Condition::ReasonCodeEquals(r) => format!("i.reasonCode == bytes32(\"{r}\")"),
        Condition::RegimeEquals(r) => format!(
            "i.verificationRegime == VerificationRegime.{}",
            regime_screaming(*r)
        ),
        Condition::SibylRegisteredActive => "i.sibylRegisteredActive".to_string(),
        Condition::ProofInstrumentSpecific => "i.proofInstrumentSpecific".to_string(),
        Condition::LexCodexPermitsPr => "i.lexcodexPermitsPr".to_string(),
    }
}

/// Generate the Foundry parity test replaying the golden corpus against the generated library.
pub fn generate_parity_test(rules: &[Rule], corpus: &[CorpusCase]) -> Result<String, CodegenError> {
    governing_order(rules)?; // validate ids/reason codes before embedding
    let hash = ruleset_hash(rules);

    let mut s = String::new();
    s.push_str(HEADER);
    s.push_str(&format!("// ruleset_sha256: {hash}\n"));
    s.push_str("// corpus: tests/parity/corpus.json (workspace root)\n");
    s.push_str("pragma solidity ^0.8.28;\n\n");
    s.push_str("import {Types} from \"../../src/core/Types.sol\";\n");
    s.push_str("import {RuleEngineV01} from \"../../src/generated/RuleEngineV01.sol\";\n\n");
    s.push_str(
        "/// @title Generated parity test (PR-003 / EN-O4): the golden corpus, on-chain.\n\
         /// @notice No forge-std dependency (repo convention): a test passes if it does not\n\
         ///         revert.\n\
         contract RuleEngineParityTest {\n",
    );
    for case in corpus {
        let fact = &case.inputs;
        let test_name = sanitize_test_name(&case.name);
        s.push_str(&format!(
            "    function test_parity_{test_name}() public pure {{\n"
        ));
        s.push_str("        RuleEngineV01.Decision memory d = RuleEngineV01.evaluate(\n");
        s.push_str("            RuleEngineV01.Inputs({\n");
        s.push_str(&format!(
            "                legSubtype: Types.LegSubtype.{},\n",
            subtype_str(fact.leg_subtype)
        ));
        s.push_str(&format!("                finality: {},\n", fact.finality));
        s.push_str(&format!(
            "                reasonCode: bytes32(\"{}\"),\n",
            fact.reason_code
        ));
        s.push_str(&format!(
            "                verificationRegime: RuleEngineV01.VerificationRegime.{},\n",
            regime_screaming(fact.verification_regime)
        ));
        s.push_str(&format!(
            "                sibylRegisteredActive: {},\n",
            fact.sibyl_registered_active
        ));
        s.push_str(&format!(
            "                proofInstrumentSpecific: {},\n",
            fact.proof_instrument_specific
        ));
        s.push_str(&format!(
            "                lexcodexPermitsPr: {}\n",
            fact.lexcodex_permits_pr
        ));
        s.push_str("            })\n        );\n");
        s.push_str(&format!(
            "        require(d.action == Types.Action.{}, \"action diverged\");\n",
            action_str(case.expected.action)
        ));
        s.push_str(&format!(
            "        require(d.forced == {}, \"forced diverged\");\n",
            case.expected.forced
        ));
        s.push_str(&format!(
            "        require(d.ruleId == bytes32(\"{}\"), \"ruleId diverged\");\n",
            case.expected.rule
        ));
        s.push_str("    }\n\n");
    }
    // Trim the trailing blank line inside the contract body.
    if s.ends_with("\n\n") {
        s.pop();
    }
    s.push_str("}\n");
    Ok(s)
}

fn sanitize_test_name(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}
