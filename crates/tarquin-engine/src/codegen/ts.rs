//! EN-O3 — the TypeScript backend: Rule IR → `exports/engine/ruleEngine.ts` (the AP-path
//! off-chain emitter, constrained to the IR subset; `tarquin-native-engine.md` §5).
//!
//! The TS types use the IR's canonical serde wire format verbatim (snake_case fields,
//! `"JUD"`, `"structured_legal_attestation"`, `"BL"`), so a corpus case's `inputs` object feeds
//! `evaluate` directly — one encoding across the corpus, Rust, and TS.

use crate::ir::{Condition, Rule};

use super::{action_str, governing_order, regime_snake, ruleset_hash, subtype_str, CodegenError};

/// Generate the off-chain evaluator module (dependency-free TypeScript).
pub fn generate(rules: &[Rule]) -> Result<String, CodegenError> {
    let ordered = governing_order(rules)?;
    let hash = ruleset_hash(rules);

    let mut s = String::new();
    s.push_str(
        "// ─────────────────────────────────────────────────────────────────────────────\n\
         // GENERATED FILE — DO NOT EDIT BY HAND.\n\
         // Generated by `tarquin-engine-gen` (crates/tarquin-engine) from the canonical\n\
         // Rule IR. Regenerate:  cargo run -p tarquin-engine --bin tarquin-engine-gen\n\
         // Drift check (CI):     cargo run -p tarquin-engine --bin tarquin-engine-gen -- --check\n\
         // ─────────────────────────────────────────────────────────────────────────────\n",
    );
    s.push_str(&format!("// ruleset_sha256: {hash}\n\n"));
    s.push_str(
        "// Total, deterministic, pure (EN-001..004): no clock, no I/O, no inference.\n\
         // Field names and enum strings are the Rule IR's canonical serde wire format.\n\n",
    );
    s.push_str(
        "export type LegSubtype = \"JUD\" | \"ADM\" | \"SUPRA\" | \"LEG_TEXT\" | \"PREC\";\n",
    );
    s.push_str(
        "export type VerificationRegime =\n  | \"structured_legal_attestation\"\n  | \"multiple_legal_attestation\"\n  | \"institutional_attestation\";\n",
    );
    s.push_str("export type Action = \"BL\" | \"HL\" | \"RW\" | \"TR\" | \"PR\";\n\n");
    s.push_str(
        "export interface Inputs {\n\
         \x20 leg_subtype: LegSubtype;\n\
         \x20 finality: number; // 1 final, 0 non-final / under appeal\n\
         \x20 reason_code: string;\n\
         \x20 verification_regime: VerificationRegime;\n\
         \x20 sibyl_registered_active: boolean;\n\
         \x20 proof_instrument_specific: boolean;\n\
         \x20 lexcodex_permits_pr: boolean;\n\
         }\n\n",
    );
    s.push_str(
        "export interface Decision {\n\
         \x20 action: Action;\n\
         \x20 forced: boolean;\n\
         \x20 rule: string;\n\
         }\n\n",
    );
    s.push_str(&format!("export const RULESET_SHA256 = \"{hash}\";\n\n"));
    s.push_str(
        "/** Semantics identical to `tarquin-engine::evaluate`: rules in governing order\n\
         \x20*  (forced first, then restrictiveness, then id), first match wins; no match\n\
         \x20*  fails closed to HL (ENG-DEFAULT-HL). */\n\
         export function evaluate(i: Inputs): Decision {\n",
    );
    for r in &ordered {
        s.push_str(&format!(
            "  // {} ({}) -> {} — parity: {}\n",
            r.id,
            if r.forced { "forced" } else { "overridable" },
            action_str(r.yields),
            r.parity_ref
        ));
        let conds: Vec<String> = r.when.iter().map(condition_ts).collect();
        s.push_str(&format!("  if ({}) {{\n", conds.join(" && ")));
        s.push_str(&format!(
            "    return {{ action: \"{}\", forced: {}, rule: \"{}\" }};\n",
            action_str(r.yields),
            r.forced,
            r.id
        ));
        s.push_str("  }\n");
    }
    s.push_str(
        "  // No rule matched: fail closed (EN-003).\n\
         \x20 return { action: \"HL\", forced: false, rule: \"ENG-DEFAULT-HL\" };\n\
         }\n",
    );
    Ok(s)
}

fn condition_ts(c: &Condition) -> String {
    match c {
        Condition::SubtypeEquals(s) => format!("i.leg_subtype === \"{}\"", subtype_str(*s)),
        Condition::FinalityEquals(f) => format!("i.finality === {f}"),
        Condition::ReasonCodeEquals(r) => format!("i.reason_code === \"{r}\""),
        Condition::RegimeEquals(r) => {
            format!("i.verification_regime === \"{}\"", regime_snake(*r))
        }
        Condition::SibylRegisteredActive => "i.sibyl_registered_active".to_string(),
        Condition::ProofInstrumentSpecific => "i.proof_instrument_specific".to_string(),
        Condition::LexCodexPermitsPr => "i.lexcodex_permits_pr".to_string(),
    }
}
